"""
Generates a repository's ``AGENTS.md`` from the generic rules this package ships and
the repository's own rules.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import StrEnum
from importlib.resources import files
from pathlib import Path

# %% file names


class RepositoryInstructionsFile(StrEnum):
    """
    The agent instruction files at a repository's root, by name.
    """

    GENERATED = "AGENTS.md"
    """
    The generated instructions agents read.
    """

    PROJECT = "AGENTS.project.md"
    """
    The rules that apply only to this repository, written by hand.
    """


class PackageResource(StrEnum):
    """
    The data files this package ships, by name.
    """

    GENERIC_INSTRUCTIONS = "AGENTS.md"
    """
    The rules that apply to any Python repository.
    """


# %% generation


@dataclass
class AgentsInstructions:
    """
    The ``AGENTS.md`` of one repository: a generated-file notice, the packaged generic
    rules and the repository's ``AGENTS.project.md``, if it has one.
    """

    repository_root: Path
    """
    The directory holding the repository's agent instruction files.
    """

    notice: str = field(
        default=(
            "<!-- Generated by `cram-development-tools agents-md`; do not edit. "
            "Write this repository's own rules in AGENTS.project.md and regenerate. -->"
        )
    )
    """
    The comment that opens the generated file.
    """

    @property
    def generated_path(self) -> Path:
        """
        The path of the generated ``AGENTS.md``.
        """
        return self.repository_root / RepositoryInstructionsFile.GENERATED

    @property
    def project_path(self) -> Path:
        """
        The path of the repository's own ``AGENTS.project.md``.
        """
        return self.repository_root / RepositoryInstructionsFile.PROJECT

    @property
    def generic_rules(self) -> str:
        """
        The packaged rules that apply to any Python repository.
        """
        return (
            files(__package__)
            .joinpath(PackageResource.GENERIC_INSTRUCTIONS)
            .read_text(encoding="utf-8")
        )

    def render(self) -> str:
        """
        Compose the content ``AGENTS.md`` must have.

        :return: The notice, the generic rules and the project rules, separated by
            blank lines.
        """
        sections = [self.notice, self.generic_rules]
        if self.project_path.is_file():
            sections.append(self.project_path.read_text(encoding="utf-8"))
        return "\n\n".join(section.strip("\n") for section in sections) + "\n"

    def is_current(self) -> bool:
        """
        :return: Whether the committed ``AGENTS.md`` equals the content it must have.
        """
        if not self.generated_path.is_file():
            return False
        return self.generated_path.read_text(encoding="utf-8") == self.render()

    def write(self) -> bool:
        """
        Write ``AGENTS.md`` with the content it must have.

        :return: Whether the file changed.
        """
        if self.is_current():
            return False
        self.generated_path.write_text(self.render(), encoding="utf-8")
        return True
